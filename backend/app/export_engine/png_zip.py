"""PNG zip export: composed pages, individual panel images, and the project JSON."""

from __future__ import annotations

import json
import zipfile
from pathlib import Path

from ..logging_config import get_logger
from ..storage import abs_path
from .render import compose_all_pages

log = get_logger("export.zip")


def export_png_zip(project, output_path: Path) -> Path:
    pages = compose_all_pages(project)
    if not pages:
        raise ValueError("nothing to export: the project has no pages")

    output_path.parent.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(output_path, "w", zipfile.ZIP_DEFLATED) as archive:
        for index, image in enumerate(pages, start=1):
            page_name = project.pages[index - 1].page_id if index - 1 < len(project.pages) else f"page_{index:02d}"
            archive.writestr(f"pages/{page_name}.png", _png_bytes(image))

        # individual panels, bubble-free, ready for reuse
        for panel in project.panels:
            if not panel.image_path:
                continue
            path = abs_path(panel.image_path)
            if path.exists():
                archive.write(path, arcname=f"panels/{panel.panel_id}.png")

        archive.writestr("project.json", project.model_dump_json(indent=2))
        archive.writestr("story.txt", project.story_text)
        archive.writestr("README.txt", _readme(project))

    log.info("png zip written: %s (%d page(s), %d panel(s))", output_path.name, len(pages), len(project.panels))
    return output_path


def _png_bytes(image) -> bytes:
    from io import BytesIO

    buffer = BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def _readme(project) -> str:
    lines = [
        f"{project.title}",
        "=" * len(project.title),
        "",
        f"Style        : {project.style}",
        f"Panels       : {len(project.panels)}",
        f"Pages        : {len(project.pages)}",
        f"Characters   : {', '.join(c.name for c in project.characters) or 'none'}",
        "",
        "Contents",
        "--------",
        "  pages/    composed pages, with lettering baked in",
        "  panels/   individual panel art, no lettering",
        "  project.json  full project data (panels, dialogue, prompts, scores)",
        "  story.txt     the source story",
        "",
        "Generated by AI ComicVerse",
    ]
    return "\n".join(lines)
